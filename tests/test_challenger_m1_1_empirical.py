class TestDateFormatsAdversarial:
    """Stress test publish_at ISO-8601 validation under diverse valid and invalid date formats."""

    @pytest.mark.parametrize(
        "valid_iso",
        [
            "2026-10-25T15:00:00Z",
            "2026-10-25T15:00:00.000Z",
            "2026-10-25T15:00:00.123456Z",
            "2026-10-25T21:00:00+09:00",
            "2026-10-25T10:00:00-05:00",
            "2026-10-25T15:00:00+00:00",
            "2026-10-25T15:00:00-00:00",
            "2026-10-25T20:30:00+05:30",  # Non-hour offset (India)
            "2026-10-25T20:45:00+05:45",  # 45-min offset (Nepal)
            "2026-10-25T12:00:00+14:00",  # Line Islands extreme offset
            "2026-10-25T12:00:00-12:00",  # Baker Island extreme offset
            "2024-02-29T12:00:00Z",        # Leap year 2024
            "2028-02-29T23:59:59+00:00",   # Leap year 2028
            "2000-02-29T00:00:00Z",        # Century leap year 2000
        ],
    )
    def test_valid_iso_formats_succeed(self, valid_iso: str) -> None:
        meta = VideoPublishMetadata(
            title="Valid Schedule",
            publish_at=valid_iso,
            privacy_status="private",
        )
        assert meta.publish_at == valid_iso

    @pytest.mark.parametrize(
        "invalid_iso,reason",
        [
            ("tomorrow", "Natural language"),
            ("next week", "Natural language"),
            ("2026/10/25 15:00:00", "Slash delimiters"),
            ("10/25/2026", "US format"),
            ("25-10-2026", "European format"),
            ("Sun, 25 Oct 2026 15:00:00 GMT", "RFC 2822 format"),
            ("1792940400", "Unix epoch timestamp"),
            ("2025-02-29T12:00:00Z", "Non-leap year Feb 29"),
            ("2026-02-29T12:00:00Z", "Non-leap year Feb 29"),
            ("1900-02-29T12:00:00Z", "Century non-leap year Feb 29"),
            ("2100-02-29T12:00:00Z", "Century non-leap year Feb 29"),
            ("2026-02-30T12:00:00Z", "Feb 30 invalid calendar date"),
            ("2026-02-31T12:00:00Z", "Feb 31 invalid calendar date"),
            ("2026-04-31T12:00:00Z", "April 31 invalid calendar date"),
            ("2026-06-31T12:00:00Z", "June 31 invalid calendar date"),
            ("2026-09-31T12:00:00Z", "September 31 invalid calendar date"),
            ("2026-11-31T12:00:00Z", "November 31 invalid calendar date"),
            ("2026-13-01T12:00:00Z", "Month 13 invalid"),
            ("2026-00-15T12:00:00Z", "Month 00 invalid"),
            ("2026-10-00T12:00:00Z", "Day 00 invalid"),
            ("2026-10-32T12:00:00Z", "Day 32 invalid"),
            ("2026-10-25T25:00:00Z", "Hour 25 invalid"),
            ("2026-10-25T12:60:00Z", "Minute 60 invalid"),
            ("2026-10-25T12:00:60Z", "Second 60 invalid"),
            ("", "Empty string"),
            ("   ", "Whitespace only"),
            ("\t\n", "Control chars whitespace only"),
            ("15:00:00", "Time only missing date"),
            ("2026-10-25T", "Trailing T without time"),
            ("T15:00:00Z", "Time with T without date"),
            ("2026-10-25T15:00:00z", "Lowercase z rejected by case-sensitive replace and fromisoformat"),
        ],
    )
    def test_invalid_iso_formats_raise_value_error(self, invalid_iso: str, reason: str) -> None:
        with pytest.raises(ValueError) as exc_info:
            VideoPublishMetadata(
                title="Bad Date",
                publish_at=invalid_iso,
                privacy_status="private",
            )
        assert "Invalid ISO-8601" in str(exc_info.value), f"Failed for {reason}: {invalid_iso}"

    @pytest.mark.parametrize(
        "malicious_input,reason",
        [
            ("'; DROP TABLE videos; --", "SQL injection string"),
            ("$(rm -rf /)", "Shell command injection"),
            ("2026-10-25T15:00:00Z\x00extra", "Null byte injection"),
            ("2026-10-25T15:00:00Z\r\nContent-Type: text/html", "CRLF header injection"),
            ("A" * 10000, "Buffer overflow / length stress"),
            ("<script>alert('xss')</script>", "XSS payload"),
        ],
    )
    def test_malicious_inputs_rejected(self, malicious_input: str, reason: str) -> None:
        with pytest.raises(ValueError) as exc_info:
            VideoPublishMetadata(
                title="Malicious Input Test",
                publish_at=malicious_input,
                privacy_status="private",
            )
        assert "Invalid ISO-8601" in str(exc_info.value), f"Failed for {reason}"

    def test_none_publish_at_allowed(self) -> None:
        """When publish_at is None, no scheduling validation should trigger."""
        meta = VideoPublishMetadata(title="Unscheduled Video", publish_at=None, privacy_status="private")
        assert meta.publish_at is None

    def test_hour_24_iso_behavior(self) -> None:
        """Adversarial check: ISO 8601-1:2019 permits 24:00:00 as end-of-day.
        Python 3.14+ datetime.fromisoformat parses 24:00:00, whereas Python < 3.14 raises ValueError.
        """
        import sys
        import pytest
        if sys.version_info >= (3, 14):
            meta = VideoPublishMetadata(
                title="Hour 24",
                publish_at="2026-10-25T24:00:00Z",
                privacy_status="private",
            )
            assert meta.publish_at == "2026-10-25T24:00:00Z"
        else:
            with pytest.raises(
                ValueError, match="Invalid ISO-8601 publish_at format"
            ):
                VideoPublishMetadata(
                    title="Hour 24",
                    publish_at="2026-10-25T24:00:00Z",
                    privacy_status="private",
                )
    def test_date_only_string_behavior(self) -> None:
        """Check behavior when date-only '2026-10-25' is provided (missing time & timezone).

        datetime.fromisoformat('2026-10-25') in Python 3.11+ parses to naive datetime(2026, 10, 25, 0, 0).
        Currently accepted by ir.py, though YouTube API requires full timestamp with timezone.
        """
        meta = VideoPublishMetadata(
            title="Date Only",
            publish_at="2026-10-25",
            privacy_status="private",
        )
        assert meta.publish_at == "2026-10-25"

    def test_naive_datetime_behavior(self) -> None:
        """Check behavior when ISO string lacks timezone ('2026-10-25T15:00:00').

        datetime.fromisoformat parses naive datetimes without error.
        Currently accepted by ir.py, though YouTube API requires explicit timezone.
        """
        meta = VideoPublishMetadata(
            title="Naive ISO",
            publish_at="2026-10-25T15:00:00",
            privacy_status="private",
        )
        assert meta.publish_at == "2026-10-25T15:00:00"

    def test_space_separated_datetime_behavior(self) -> None:
        """Check behavior when space separates date and time ('2026-10-25 15:00:00Z')."""
        meta = VideoPublishMetadata(
            title="Space Separated",
            publish_at="2026-10-25 15:00:00Z",
            privacy_status="private",
        )
        assert meta.publish_at == "2026-10-25 15:00:00Z"

    def test_non_string_publish_at_raises_value_or_type_error(self) -> None:
        """Check behavior when non-string type is passed to publish_at."""
        with pytest.raises((ValueError, TypeError, AttributeError)):
            VideoPublishMetadata(
                title="Non-string Int",
                publish_at=123456789,  # type: ignore
                privacy_status="private",
            )


